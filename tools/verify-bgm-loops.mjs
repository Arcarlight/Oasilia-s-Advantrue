// Cross-check the loop span the game actually uses for every BGM track against
// the decoded length of the file.
//
// Why this exists: src/core/bgm.js loops [loopStart, loopStart+loopLength) and
// needs that span to end at (or within 0.6s of) end-of-file. If it points
// somewhere in the middle of the music, the tail is never heard — which only ever
// shows up as "循环点听起来不对" much later. The numbers come from the
// LOOPSTART/LOOPLENGTH vorbis comments that ship inside the ogg files (no file is
// re-cut), and this is the gate that keeps them honest: it checks them against the
// audio itself, including the case where the comment is stale and has been
// dropped on purpose (battle_storm.ogg claims 941s of music in a 125s file, so
// assets/audio/bgm/manifest.json — generated by tools/fetch-bgm.mjs and baked into
// the generated BGM_LOOPS table — records no loop span for it).
//
// Usage: node tools/verify-bgm-loops.mjs [key ...]
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'assets', 'audio', 'bgm');
const FFMPEG = process.env.FFMPEG || 'D:\\FormatFact\\FormatFactory\\ffmpeg.exe';
const RATE = 22050;
const TOL = 0.6;

function decodedSeconds(file) {
  const pcm = execFileSync(FFMPEG, ['-v', 'error', '-i', file, '-ac', '1', '-ar', String(RATE), '-f', 's16le', '-'],
    { maxBuffer: 1 << 30, stdio: ['ignore', 'pipe', 'ignore'] });
  return pcm.length / 2 / RATE;
}

/**
 * The span the game uses, taken from the same generated table the runtime reads
 * (src/core/bgm.js -> BGM_LOOPS), falling back to the file's own comments.
 */
function loopOf(key, ours, file) {
  // The generated table uses { start, length, rate } (sample counts), and stores
  // null for a track whose loop comment did not hold up.
  if (ours && ours.start != null && ours.length > 0) {
    return { start: ours.start, length: ours.length, rate: ours.rate ?? 44100 };
  }
  if (ours !== undefined) return null;          // recorded as "no loop span"
  const buf = fsSync.readFileSync(file);        // not in the table: read the file
  const s = buf.subarray(0, Math.min(buf.length, 65536)).toString('latin1');
  // Matched independently: the two comments are neither guaranteed adjacent nor
  // in order (battle_storm.ogg writes LOOPLENGTH first).
  const st = /LOOPSTART=(\d+)/.exec(s);
  const ln = /LOOPLENGTH=(\d+)/.exec(s);
  return st && ln ? { start: Number(st[1]), length: Number(ln[1]), rate: 44100 } : null;
}

const only = process.argv.slice(2);
const files = (await fs.readdir(DIR)).filter((f) => f.endsWith('.ogg'))
  .filter((f) => !only.length || only.includes(path.basename(f, '.ogg')))
  .sort();
if (!files.length) { console.error('no ogg files matched'); process.exit(2); }

let { BGM_LOOPS = {} } = await import('../src/core/bgm.js');
if (!BGM_LOOPS || typeof BGM_LOOPS !== 'object') BGM_LOOPS = {};

let bad = 0;
let missing = 0;
let checked = 0;
for (const f of files) {
  const full = path.join(DIR, f);
  const key = path.basename(f, '.ogg');
  const padded = key.padEnd(15);
  const ours = Object.prototype.hasOwnProperty.call(BGM_LOOPS, key) ? BGM_LOOPS[key] : undefined;
  const meta = loopOf(key, ours, full);
  const dur = decodedSeconds(full);
  if (!meta) {
    missing++;
    console.log(`  ? ${padded} no loop span -> the game loops the whole ${dur.toFixed(1)}s file`);
    continue;
  }
  checked++;
  const ls = meta.start / meta.rate;
  const le = (meta.start + meta.length) / meta.rate;
  const delta = dur - le;
  if (!(le > ls) || Math.abs(delta) > TOL) {
    bad++;
    console.log(`  x ${padded} loop ${ls.toFixed(2)}~${le.toFixed(2)}s but file is ${dur.toFixed(2)}s (gap ${delta.toFixed(2)}s) @${meta.rate}Hz`);
  } else {
    console.log(`  v ${padded} intro ${ls.toFixed(2)}s + loop ${(le - ls).toFixed(2)}s = ${le.toFixed(2)}s / file ${dur.toFixed(2)}s`);
  }
}

console.log('');
console.log(`LOOPCHECK_OK checked=${checked} withoutLoopSpan=${missing} bad=${bad}`);
if (bad) process.exit(1);
