// 界面上那几张「小词表」：属性全名 / 属性短标签 / 属性悬停说明。
//
// 为什么单独放一份（而不是留在 game.js / battle-view.js 里）：
//   · tools/build-i18n.mjs 生成「待翻清单」的方式是**扫源码里的中文**，而这几张表
//     在代码里是**查表读出来**的（t(STAT_NAMES[k])）—— 中文原文躺在模块里，
//     扫描器看不见「谁在用它们」，于是永远进不了清单、永远没人翻、界面上永远中文；
//   · 界面模块（battle-view.js）import 了 DOM，工具在 node 里根本跑不起来，
//     所以表要挪进一个**纯数据**模块：这里不许 import 任何会碰 DOM 的东西。
//   运行时照旧：src/core/i18n-tables.js 把它们登记进 I18N_WORD_TABLES 交给工具，
//   代码里继续写 t(STAT_NAMES[k]) / t(STAT_TIP[label]) 按当前语言查表。
//
// 改这里的文案 = 改了中文原文（也就是**翻译键**）：旧译文会变成孤儿，
// build-i18n 的体检会直接报出来，不会静默漂移。
//
// 键一律写成带引号的字符串：清单是按「源码里的引号字面量」收的，键也在收集范围内
// （键本身同样会显示在界面上，比如短标签「攻」）。

